#!/usr/bin/env python3
"""Assemble the P5 CAD-derived CSG renderer with a deterministic studio shader.

The new geometry is generated by capture_csg/build_csg_shader. This assembler
changes display finishes, lighting and camera, never mechanical dimensions.
"""
from pathlib import Path
import hashlib,json,re

ROOT=Path(__file__).resolve().parents[1]
ENG=ROOT.parent/'ARX-6-P5-Engineering'
SRC=ROOT/'source'

def finish(record):
    name=record['name'].lower()
    mat=record['material']
    if any(s in name for s in ['motor','gearhead','brake_stator','sensor','cable','guard']): mat=2
    if any(s in name for s in ['bearing_housing','pedestal','yoke','root_ear','roll_fork','bend_cradle','structural','folded_frame','belt_case','belt_housing','belt_cover','front_plate']): mat=1
    if any(s in name for s in ['pulley','index_disk','stop_target']): mat=6
    if 'belt' in name and not any(s in name for s in ['pulley','cover','plate','housing','case','guard','frame','bolt','shaft','screw','mount','support']): mat=5
    if any(s in name for s in ['screw','bolt','shaft','key','ring','pin_','spring']): mat=4
    if 'rubber' in name or 'liner' in name or 'pad' in name: mat=5
    return int(mat)

objects=json.loads((SRC/'compiled-csg.json').read_text())['objects']
finishes=[finish(o) for o in objects]
light=(SRC/'lighting.glsl').read_text()
code=f'const int P5_FINISH[{len(objects)}]=int[{len(objects)}]('+','.join(map(str,finishes))+');\n'
light=light.replace('RobotMaterial robotMaterial(Hit hit,vec3 position) {',code+'''RobotMaterial robotMaterial(Hit hit,vec3 position) {
    float finishID=hit.id;
    if(hit.part>=1000.&&hit.part<float(1000+P5_FINISH.length())) finishID=float(P5_FINISH[int(hit.part)-1000]);
''')
a=light.index('RobotMaterial robotMaterial(');b=light.index('vec3 robotFresnel',a)
light=light[:a]+light[a:b].replace('if(hit.id<','if(finishID<')+light[b:]
light=light.replace('p=vec3(-3.4,5.3,4.4);','p=vec3(-2.7,5.5,4.5);')
light=light.replace('halfSize=vec2(2.25,1.60);','halfSize=vec2(2.6,1.65);')
light=light.replace('radiance=vec3(7.55,7.20,6.67);','radiance=vec3(5.8,5.6,5.25);')
light=light.replace('p=vec3(-3.2,1.25,2.5);','p=vec3(4.3,2.6,2.4);')
light=light.replace('halfSize=vec2(2.00,1.05);','halfSize=vec2(1.1,2.0);')
light=light.replace('radiance=vec3(2.1,2.24,2.50);','radiance=vec3(3.0,3.15,3.4);')
light=light.replace('p=vec3(-1.2,5.1,-3.4);','p=vec3(-1.8,4.6,-3.2);')
light=light.replace('halfSize=vec2(.60,2.00);','halfSize=vec2(1.15,2.0);')
light=light.replace('radiance=vec3(5.00,5.40,6.00);','radiance=vec3(5.8,6.0,6.3);')
light=light.replace('m.base=vec3(.62,.63,.62)','m.base=vec3(.56,.555,.535)')
light=light.replace('m.roughness=.295+.013*finish+.018*fine;','m.roughness=.25+.012*finish+.016*fine;')
light=light.replace('m.base=vec3(.012,.016,.021)','m.base=vec3(.038,.043,.050)')
light=light.replace('m.roughness=.335+.028*finish+.020*fine;','m.roughness=.27+.022*finish+.016*fine;')
light=light.replace('m.roughness=.30+.025*finish+.024*fine;','m.roughness=.26+.020*finish+.016*fine;')
light=light.replace('m.anisotropy=.62;','m.anisotropy=.42;')
light=light.replace('m.base=vec3(.42,.145,.035);','m.base=vec3(.38,.19,.07);')
light=light.replace('m.f0=vec3(.77,.345,.105);','m.f0=vec3(.69,.40,.18);')
light=light.replace('vec3 normal=normalize(vec3(.65,1.15,0.0)-p);','''vec3 lightTarget=vec3(.65,1.15,0.);
    if(u_camera_override!=0&&u_inspect>0) {
        vec3 view=normalize(u_camera_origin-u_camera_target);
        vec3 right=normalize(cross(vec3(0,1,0),view));
        vec3 up=cross(view,right);
        float scale=clamp(length(u_camera_origin-u_camera_target)*.60,.7,4.);
        vec3 offset=index==0?vec3(-1.35,1.75,2.30):index==1?vec3(1.8,.45,1.65):vec3(-.75,1.65,-1.6);
        lightTarget=u_camera_target;
        p=lightTarget+scale*(right*offset.x+up*offset.y+view*offset.z);
        halfSize*=scale*.65;
    }
    vec3 normal=normalize(lightTarget-p);''')

# Every camera sample uses a complete area-light quadrature. A varying camera
# sample count therefore never changes the emitter's intensity or phase.
a=light.index('vec2 robotGaussNode(');b=light.index('float robotLambda(',a)
light=light[:a]+'''vec2 robotGaussNode(int index) {
    int k=index/2;
    if(k==0) return vec2(-.9061798459,.2369268851);
    if(k==1) return vec2(-.5384693101,.4786286705);
    if(k==2) return vec2(0.,.5688888889);
    if(k==3) return vec2(.5384693101,.4786286705);
    return vec2(.9061798459,.2369268851);
}
'''+light[b:]
a=light.index('        float visibility=softShadow(');b=light.index('        vec3 integral=',a)
light=light[:a]+'''        float visibility=0.;
#ifndef P5_SHADOW_SAMPLES
#define P5_SHADOW_SAMPLES 2
#endif
        for(int si=0;si<P5_SHADOW_SAMPLES;si++) {
            vec2 sv=si==0?vec2(-.38,.31):si==1?vec2(.38,-.31):si==2?vec2(.36,.37):vec2(-.36,-.37);
            if(P5_SHADOW_SAMPLES==1) sv=vec2(0.);
            vec3 sp=light.position+light.u*sv.x*light.halfSize.x+light.v*sv.y*light.halfSize.y;
            visibility+=softShadow(position+n*max(bias,.00035),sp);
        }
        visibility/=float(P5_SHADOW_SAMPLES);
        float weight=1.;
'''+light[b:]
light=light.replace('robotGaussNode(2*y+robotLightPhase/2)','robotGaussNode(2*y)')
light=light.replace('robotGaussNode(2*x+robotLightPhase%2)','robotGaussNode(2*x)')

# Skip only area lights whose complete rectangle contributes zero. The
# conservative guard also covers floating-point error near either horizon.
# Keep all original quadrature and shadow samples for every retained light.
facing_hook='''        vec3 lightNormal=cross(light.u,light.v);
        float visibility=0.;'''
if light.count(facing_hook)!=1:raise RuntimeError('Missing unique P5 light-facing hook')
light=light.replace(facing_hook,'''        vec3 lightNormal=cross(light.u,light.v);
        // Conservative rectangle bounds: these lights contribute exactly
        // zero when every emitter sample is below either facing hemisphere.
        vec3 emitterDelta=light.position-position;
        float receiverUpper=dot(n,emitterDelta)+abs(dot(n,light.u))*light.halfSize.x+abs(dot(n,light.v))*light.halfSize.y;
        float emitterUpper=-dot(lightNormal,emitterDelta)+abs(dot(lightNormal,light.u))*light.halfSize.x+abs(dot(lightNormal,light.v))*light.halfSize.y;
        float facingGuard=1e-5*(1.+length(emitterDelta)+light.halfSize.x+light.halfSize.y);
        if(receiverUpper < -facingGuard || emitterUpper < -facingGuard) continue;
        float visibility=0.;''')

(SRC/'lighting-p5.glsl').write_text(light)
core=(ENG/'render/original/core.glsl').read_text()
kin=(SRC/'kinematics.glsl').read_text()
runtime=(SRC/'geometry-runtime.glsl').read_text()
camera=(SRC/'camera-p5.glsl').read_text()
camera_uniforms='\n'.join(re.findall(r'^uniform[^;]+;',camera,re.M))
camera=re.sub(r'^uniform[^;]+;\n','',camera,flags=re.M)
source='\n\n'.join([core,camera_uniforms,kin,(SRC/'geometry-constants.glsl').read_text(),runtime,light,camera])
out=ROOT/'ARX-6-P5-Live.glsl';out.write_text(source)
report={'revision':'P5','shader':out.name,'shader_sha256':hashlib.sha256(source.encode()).hexdigest(),'objects':len(objects),'geometry_source':'CAD construction replay; one fullscreen fragment program; no robot meshes or image material textures','display_finishes':[{'name':o['name'],'substrate':o['material'],'display_finish':f} for o,f in zip(objects,finishes)]}
(ROOT/'reports/assembly-p5.json').write_text(json.dumps(report,indent=2))
print(json.dumps({k:v for k,v in report.items() if k!='display_finishes'}))
