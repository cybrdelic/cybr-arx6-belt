        gp('glUniformMatrix3fv',None,I,I,B,C.POINTER(F));gp('glUniformMatrix4fv',None,I,I,B,C.POINTER(F))
        gp('glGenVertexArrays',None,I,C.POINTER(U));gp('glBindVertexArray',None,U)
        gp('glGenTextures',None,I,C.POINTER(U));gp('glBindTexture',None,U,U)
        gp('glTexImage2D',None,U,I,I,I,I,I,U,U,V);gp('glTexParameteri',None,U,U,I)
        gp('glGenFramebuffers',None,I,C.POINTER(U));gp('glBindFramebuffer',None,U,U)
        gp('glFramebufferTexture2D',None,U,U,U,U,I);gp('glCheckFramebufferStatus',U,U)
        gp('glViewport',None,I,I,I,I);gp('glDrawArrays',None,U,I,I);gp('glReadPixels',None,I,I,I,I,U,U,V)
        gp('glFinish',None);gp('glDisable',None,U);gp('glPixelStorei',None,U,I)
        if geometry_buffers:
            gp('glGenBuffers',None,I,C.POINTER(U));gp('glBindBuffer',None,U,U);gp('glBufferData',None,U,C.c_ssize_t,V,U);gp('glBindBufferBase',None,U,U,U)
            gp('glGetProgramResourceIndex',U,U,U,P);gp('glGetProgramResourceiv',None,U,U,U,I,C.POINTER(U),I,C.POINTER(I),C.POINTER(I))
        start=time.monotonic()
        version='430' if geometry_buffers else '330'
        vertex='#version '+version+'''\nvoid main(){vec2 p=vec2(float((gl_VertexID<<1)&2),float(gl_VertexID&2));gl_Position=vec4(p*2.-1.,0.,1.);}'''
