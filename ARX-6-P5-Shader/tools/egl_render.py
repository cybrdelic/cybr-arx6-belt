#!/usr/bin/env python3
"""Dependency-light desktop GLSL renderer: system EGL/OpenGL + NumPy/Pillow.

Creates a surfaceless OpenGL context. No model buffers or textures are uploaded.
Each image is generated by one fullscreen triangle and the supplied fragment
program. The only texture is the floating-point render destination.
"""
from __future__ import annotations
import argparse, ctypes as C, ctypes.util, hashlib, json, os, sys, time
from pathlib import Path
import numpy as np
from PIL import Image

os.environ.setdefault('MESA_SHADER_CACHE_DIR',str(Path(__file__).resolve().parents[1]/'.mesa-cache'))
